-- =============================================================================
-- Apreu v2 · BD maestra (PostgreSQL 16) · propiedad de superadmin-api
--   tenants: registro de colegios (apreu-api solo la lee; db_name NULL => apreu_<slug>).
--   users:   operadores de la plataforma (role = 'superadmin'); misma forma que
--            la tabla users de cada colegio.
-- Equivale a database/mariadb/master-schema.sql + master-migrations/001 (y a la
-- tabla users que superadmin-api ya usaba en la BD maestra MariaDB).
-- Idempotente. Uso: psql -v ON_ERROR_STOP=1 -d apreu_master -f master-schema.sql
-- La BD maestra trabaja en UTC (ADR-0008).
-- =============================================================================

SET client_min_messages = warning;

-- ------------------------------------------------------------------
-- Extensiones y funciones comunes (ADR-0008, "Colación y búsquedas")
-- ------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;

-- unaccent() es STABLE (depende del search_path); este envoltorio fija el
-- diccionario y es IMMUTABLE para poder usarlo en índices de expresión.
-- Búsquedas: f_unaccent(col) ILIKE f_unaccent($1).
CREATE OR REPLACE FUNCTION f_unaccent(text)
  RETURNS text
  LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
AS $func$
  SELECT public.unaccent('public.unaccent'::regdictionary, $1)
$func$;

-- Equivalente de "ON UPDATE current_timestamp()" de MariaDB: actualiza
-- updated_at cuando la fila cambia y la sentencia no fijó otro valor.
CREATE OR REPLACE FUNCTION set_updated_at()
  RETURNS trigger
  LANGUAGE plpgsql
AS $func$
BEGIN
  IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at AND NEW IS DISTINCT FROM OLD THEN
    NEW.updated_at := statement_timestamp();
  END IF;
  RETURN NEW;
END
$func$;

-- tenants
CREATE TABLE IF NOT EXISTS tenants (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  slug varchar(60) NOT NULL,
  name varchar(200) NOT NULL,
  admin_email varchar(150),
  admin_phone varchar(30),
  status varchar(10) NOT NULL DEFAULT 'active',
  tables_created boolean NOT NULL DEFAULT false,
  db_name varchar(64),
  trial_ends_at date,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT tenants_pkey PRIMARY KEY (id),
  CONSTRAINT tenants_status_check CHECK (status IN ('active', 'suspended', 'trial'))
);
CREATE INDEX IF NOT EXISTS tenants_deleted_at_idx ON tenants (deleted_at);
CREATE INDEX IF NOT EXISTS tenants_status_idx ON tenants (status);
CREATE UNIQUE INDEX IF NOT EXISTS tenants_slug_key ON tenants (slug);
DROP TRIGGER IF EXISTS tenants_set_updated_at ON tenants;
CREATE TRIGGER tenants_set_updated_at BEFORE UPDATE ON tenants FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- users
CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  name varchar(150) NOT NULL,
  email varchar(150) NOT NULL,
  password varchar(255) NOT NULL,
  role varchar(10) NOT NULL DEFAULT 'admin',
  avatar varchar(255),
  is_active boolean NOT NULL DEFAULT true,
  last_login timestamptz,
  must_change_password boolean NOT NULL DEFAULT false,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  CONSTRAINT users_pkey PRIMARY KEY (id),
  CONSTRAINT users_role_check CHECK (role IN ('superadmin', 'admin', 'finance', 'hr', 'teacher', 'parent', 'student', 'employee'))
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_key ON users (lower(email));
CREATE INDEX IF NOT EXISTS users_role_idx ON users (role);
DROP TRIGGER IF EXISTS users_set_updated_at ON users;
CREATE TRIGGER users_set_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();
