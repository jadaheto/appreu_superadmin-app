import { BcryptPasswordHasher } from './password-hasher.js';

describe('BcryptPasswordHasher', () => {
  const hasher = new BcryptPasswordHasher();

  it('hashes and verifies a password', async () => {
    const hash = await hasher.hash('Secreta123*');
    expect(hash).not.toContain('Secreta123*');
    await expect(hasher.verify('Secreta123*', hash)).resolves.toBe(true);
    await expect(hasher.verify('otra', hash)).resolves.toBe(false);
  });

  it('accepts hashes generated by PHP password_hash ($2y$)', async () => {
    // password_hash('Apreu2024!', PASSWORD_BCRYPT)
    const phpHash = (await hasher.hash('Apreu2024!')).replace(/^\$2b\$/, '$2y$');
    await expect(hasher.verify('Apreu2024!', phpHash)).resolves.toBe(true);
  });

  it('rejects empty hashes', async () => {
    await expect(hasher.verify('x', '')).resolves.toBe(false);
  });
});
