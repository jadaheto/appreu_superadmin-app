/**
 * Identity of a persisted entity. `null` means the entity is new and has not
 * been assigned an id by the persistence layer yet.
 */
export type EntityId = number | null;

/**
 * Base class for domain entities.
 *
 * Entities are compared by identity, not by attributes. Subclasses keep their
 * state in the protected `props` object and expose it through intention
 * revealing getters/methods, never through public setters.
 */
export abstract class Entity<TProps extends object> {
  protected constructor(
    protected _id: EntityId,
    protected readonly props: TProps,
  ) {}

  get id(): EntityId {
    return this._id;
  }

  /** True while the entity has not been persisted. */
  get isNew(): boolean {
    return this._id === null;
  }

  /**
   * Assigns the identity generated by the persistence layer.
   * Can only be called once.
   */
  assignId(id: number): void {
    if (this._id !== null) {
      throw new Error('La entidad ya tiene un identificador asignado.');
    }
    this._id = id;
  }

  equals(other?: Entity<TProps>): boolean {
    if (!other || other.constructor !== this.constructor) return false;
    if (this._id === null || other._id === null) return this === other;
    return this._id === other._id;
  }
}
