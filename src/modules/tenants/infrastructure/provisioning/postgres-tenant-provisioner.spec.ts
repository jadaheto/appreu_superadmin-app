import {
  BusinessRuleViolationError,
  ConflictError,
  ExternalServiceError,
} from '../../../../shared/domain/domain-error.js';
import { loadEnvironment } from '../../../../shared/infrastructure/config/environment.js';
import { FakeTenantDatabaseConnector, pgError } from '../../../../shared/testing/fake-sql.js';
import { PostgresTenantProvisioner, SCHEMA_LOCK_SQL, SCHEMA_MIGRATIONS_DDL } from './postgres-tenant-provisioner.js';
import type { SqlScript } from './schema-script-loader.js';

const baseEnv = {
  SUPERADMIN_JWT_SECRET: 's',
  MASTER_DB_HOST: 'm',
  MASTER_DB_USER: 'u',
  MASTER_DB_NAME: 'master',
  TENANT_DB_HOST: 't',
  TENANT_DB_ADMIN_USER: 'prov',
};
const env = loadEnvironment(baseEnv);

const SCHEMA = `-- Esquema consolidado
CREATE EXTENSION IF NOT EXISTS unaccent;
CREATE TABLE users (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
CREATE TABLE settings (key varchar(50) PRIMARY KEY, value text);
INSERT INTO users (name, email, role) VALUES ('Super', 'root@apreu.co', 'superadmin');
`;

const schemaScript = (content = SCHEMA): SqlScript => ({
  version: 'tenant-schema',
  name: 'tenant-schema.sql',
  content,
  baseline: true,
});

const PREAMBLE = ['ALTER DATABASE "apreu_norte" SET "TimeZone" TO \'America/Bogota\'', SCHEMA_MIGRATIONS_DDL];

describe('PostgresTenantProvisioner', () => {
  let connector: FakeTenantDatabaseConnector;
  let scripts: SqlScript[];
  let provisioner: PostgresTenantProvisioner;

  beforeEach(() => {
    connector = new FakeTenantDatabaseConnector();
    scripts = [schemaScript()];
    provisioner = new PostgresTenantProvisioner(connector, { load: async () => scripts }, env);
  });

  describe('databaseExists', () => {
    it('queries pg_database with a bound parameter', async () => {
      connector.respond = (sql) => (sql.includes('pg_database') ? [{ datname: 'apreu_norte' }] : []);
      await expect(provisioner.databaseExists('apreu_norte')).resolves.toBe(true);
      expect(connector.queries[0]).toMatchObject({
        session: 'server',
        sql: 'SELECT datname FROM pg_database WHERE datname = $1',
        params: ['apreu_norte'],
      });
      expect(connector.closed).toBe(1);
    });

    it.each(['apreu_x"; DROP', 'otro_norte', 'APREU_X', 'apreu_' + 'x'.repeat(60)])(
      'refuses unmanaged or unsafe names: %s',
      async (name) => {
        await expect(provisioner.databaseExists(name)).rejects.toThrow();
        expect(connector.queries).toEqual([]);
      },
    );
  });

  describe('createDatabase', () => {
    it('creates the database with a quoted identifier and without IF NOT EXISTS (orphans are never reused)', async () => {
      await provisioner.createDatabase('apreu_norte');
      expect(connector.sqlOf('server')).toEqual([`CREATE DATABASE "apreu_norte" ENCODING 'UTF8' TEMPLATE template0`]);
    });

    it('assigns the configured owner role', async () => {
      provisioner = new PostgresTenantProvisioner(
        connector,
        { load: async () => scripts },
        loadEnvironment({ ...baseEnv, TENANT_DB_OWNER: 'apreu_app' }),
      );
      await provisioner.createDatabase('apreu_norte');
      expect(connector.sqlOf()).toEqual([
        `CREATE DATABASE "apreu_norte" OWNER "apreu_app" ENCODING 'UTF8' TEMPLATE template0`,
      ]);
    });

    it('maps "duplicate_database" to a conflict', async () => {
      connector.respond = () => pgError('42P04');
      await expect(provisioner.createDatabase('apreu_norte')).rejects.toBeInstanceOf(ConflictError);
    });

    it('explains missing privileges without leaking driver details', async () => {
      connector.respond = () => pgError('42501');
      const error = await provisioner.createDatabase('apreu_norte').catch((e) => e);
      expect(error).toBeInstanceOf(ExternalServiceError);
      expect(error.message).toMatch(/privilegios/);
      expect(error.message).not.toContain('db-secret');
    });

    it('maps connection failures', async () => {
      connector.failOpen = pgError('ECONNREFUSED');
      await expect(provisioner.createDatabase('apreu_norte')).rejects.toBeInstanceOf(ExternalServiceError);
    });
  });

  describe('installSchema', () => {
    it('runs the schema in one transaction, records its version and never seeds users', async () => {
      const report = await provisioner.installSchema('apreu_norte');

      expect(connector.opened).toEqual(['provisioning:apreu_norte']);
      expect(connector.sqlOf()).toEqual([
        ...PREAMBLE,
        'BEGIN',
        SCHEMA_LOCK_SQL,
        'SELECT 1 FROM schema_migrations WHERE version = $1',
        'CREATE EXTENSION IF NOT EXISTS unaccent',
        'CREATE TABLE users (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)',
        'CREATE TABLE settings (key varchar(50) PRIMARY KEY, value text)',
        'INSERT INTO schema_migrations (version) VALUES ($1)',
        'COMMIT',
      ]);
      expect(connector.queries.at(-2)?.params).toEqual(['tenant-schema']);
      expect(report).toEqual({
        statementsExecuted: 3,
        skipped: [expect.any(String)],
        migrationsApplied: [],
        alreadyApplied: [],
      });
      expect(connector.closed).toBe(1);
    });

    it('applies migrations after the schema, each in its own transaction', async () => {
      scripts.push({
        version: '001-finance-x',
        name: '001-finance-x.sql',
        content: 'ALTER TABLE settings ADD COLUMN IF NOT EXISTS x integer;',
        baseline: false,
      });
      const report = await provisioner.installSchema('apreu_norte');
      expect(report.migrationsApplied).toEqual(['001-finance-x']);
      expect(connector.sqlOf().filter((sql) => sql === 'BEGIN')).toHaveLength(2);
      expect(connector.sqlOf().slice(-3)).toEqual([
        'ALTER TABLE settings ADD COLUMN IF NOT EXISTS x integer',
        'INSERT INTO schema_migrations (version) VALUES ($1)',
        'COMMIT',
      ]);
    });

    it('skips versions already recorded in schema_migrations (re-applying is safe)', async () => {
      connector.respond = (sql, params) =>
        sql.startsWith('SELECT 1 FROM schema_migrations') && params[0] === 'tenant-schema' ? [{ '?column?': 1 }] : [];
      scripts.push({ version: '001-a', name: '001-a.sql', content: 'SELECT 1;', baseline: false });

      const report = await provisioner.installSchema('apreu_norte');

      expect(report.alreadyApplied).toEqual(['tenant-schema']);
      expect(report.migrationsApplied).toEqual(['001-a']);
      expect(connector.sqlOf()).not.toContain('CREATE EXTENSION IF NOT EXISTS unaccent');
      expect(connector.sqlOf()).toContain('ROLLBACK');
    });

    it('stops at the first failing statement, rolls back the file and reports where', async () => {
      connector.respond = (sql) => (sql.startsWith('CREATE TABLE settings') ? pgError('42601') : []);
      const error = await provisioner.installSchema('apreu_norte').catch((e) => e);
      expect(error).toBeInstanceOf(BusinessRuleViolationError);
      expect(error.message).toBe('Falló la sentencia 3 de tenant-schema.sql: 42601.');
      expect(connector.sqlOf().at(-1)).toBe('ROLLBACK');
      expect(connector.sqlOf()).not.toContain('INSERT INTO schema_migrations (version) VALUES ($1)');
      expect(connector.closed).toBe(1);
    });

    it('rejects schemas with statements that escape the database', async () => {
      scripts[0] = schemaScript('CREATE DATABASE otra; CREATE TABLE x (id integer);');
      await expect(provisioner.installSchema('apreu_norte')).rejects.toThrow(
        expect.objectContaining({ code: 'FORBIDDEN_SQL' }),
      );
      expect(connector.queries).toEqual([]);
    });

    it('acts as the owner role and grants read access to the analytics account', async () => {
      provisioner = new PostgresTenantProvisioner(
        connector,
        { load: async () => scripts },
        loadEnvironment({ ...baseEnv, TENANT_DB_OWNER: 'apreu_app', TENANT_DB_READER_USER: 'sa_reader' }),
      );
      await provisioner.installSchema('apreu_norte');
      const sql = connector.sqlOf();
      expect(sql[0]).toBe('SET ROLE "apreu_app"');
      expect(sql.slice(-5)).toEqual([
        'REVOKE CONNECT, TEMPORARY ON DATABASE "apreu_norte" FROM PUBLIC',
        'GRANT CONNECT ON DATABASE "apreu_norte" TO "sa_reader"',
        'GRANT USAGE ON SCHEMA public TO "sa_reader"',
        'GRANT SELECT ON ALL TABLES IN SCHEMA public TO "sa_reader"',
        'ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO "sa_reader"',
      ]);
    });
  });

  describe('bootstrapSchool', () => {
    const director = {
      name: 'Director IE Norte',
      email: 'D@Norte.co',
      passwordHash: '$2b$12$abcdefghijklmnopqrstuv',
    };

    it('creates the director with a parameterized statement and a PHP compatible hash', async () => {
      const report = await provisioner.bootstrapSchool('apreu_norte', {
        schoolName: 'IE Norte',
        director,
      });

      expect(report).toEqual({ superadminsRemoved: 0 });
      expect(connector.sqlOf()[0]).toBe('BEGIN');
      const insert = connector.queries.find((q) => q.sql.startsWith('INSERT INTO users'));
      expect(insert?.params).toEqual(['Director IE Norte', 'd@norte.co', '$2y$12$abcdefghijklmnopqrstuv']);
      expect(insert?.sql).toContain('VALUES ($1, $2, $3');
      expect(insert?.sql).toContain('must_change_password');
      const setting = connector.queries.find((q) => q.sql.includes('school_name'));
      expect(setting?.sql).toContain('ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value');
      expect(setting?.params).toEqual(['IE Norte']);
      expect(connector.sqlOf().at(-1)).toBe('COMMIT');
    });

    it('removes seeded superadmins if any slipped in', async () => {
      connector.respond = (sql) => (sql.startsWith('SELECT COUNT(*)::int') ? [{ total: 2 }] : []);
      const report = await provisioner.bootstrapSchool('apreu_norte', {
        schoolName: 'IE Norte',
        director,
      });
      expect(report.superadminsRemoved).toBe(2);
      expect(connector.sqlOf()).toContain("DELETE FROM users WHERE role = 'superadmin'");
    });

    it('rolls back on failure', async () => {
      connector.respond = (sql) => (sql.startsWith('INSERT INTO users') ? pgError('23505') : []);
      await expect(
        provisioner.bootstrapSchool('apreu_norte', {
          schoolName: 'IE Norte',
          director,
        }),
      ).rejects.toBeInstanceOf(ExternalServiceError);
      expect(connector.sqlOf()).toContain('ROLLBACK');
    });
  });

  it('drops only managed databases, closing their open sessions', async () => {
    await provisioner.dropDatabase('apreu_norte');
    expect(connector.sqlOf('server')).toEqual(['DROP DATABASE IF EXISTS "apreu_norte" WITH (FORCE)']);
    await expect(provisioner.dropDatabase('postgres')).rejects.toThrow(/no pertenece/);
  });
});
